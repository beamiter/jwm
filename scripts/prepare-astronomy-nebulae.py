#!/usr/bin/env python3
"""Build the offline observed deep-sky atlas and its shared CPU/GPU catalogue.

Download the source_image URLs in deep-sky-catalog.json separately as <id>.jpg.
This script verifies those bytes; the compositor never downloads images.
--check needs no source downloads and checks the committed generated catalogue.
"""

import argparse
import hashlib
import json
import math
from pathlib import Path
import subprocess
import textwrap

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets/astronomy"
SHADERS = ROOT / "src/backend/x11/compositor/shaders"
RUST = ROOT / "src/backend/compositor_common/deep_sky_catalog.rs"
TILE = 1024


def galactic(v):
    # ICRS -> IAU Galactic, rearranged to the sky shader's (X, Z, Y) frame.
    return [sum(a * b for a, b in zip(row, v)) for row in (
        (-0.054875560416, -0.873437090235, -0.483835015549),
        (-0.867666149019, -0.198076373431, 0.455983776175),
        (0.494109427876, -0.444829629960, 0.746982244497),
    )]


def geometry(target):
    ra, dec, angle = map(math.radians, (
        target["ra_degrees"], target["dec_degrees"], target["north_left_degrees"]
    ))
    direction = galactic([math.cos(dec) * math.cos(ra), math.cos(dec) * math.sin(ra), math.sin(dec)])
    east = galactic([-math.sin(ra), math.cos(ra), 0])
    north = galactic([-math.sin(dec) * math.cos(ra), -math.sin(dec) * math.sin(ra), math.cos(dec)])
    right = [-math.cos(angle) * e - math.sin(angle) * n for e, n in zip(east, north)]
    up = [-math.sin(angle) * e + math.cos(angle) * n for e, n in zip(east, north)]
    distance = target["distance_ly"]
    return {
        "position_ly": [x * distance for x in direction],
        "right": right,
        "up": up,
        "half_size_ly": [distance * math.tan(math.radians(x / 60) / 2) for x in target["field_arcmin"]],
        "atlas_rect": target["atlas_rect"],
    }


def generated(targets):
    entries = [geometry(t) for t in targets]
    rust = "// Generated by scripts/prepare-astronomy-nebulae.py; edit deep-sky-catalog.json.\n"
    rust += f"pub(crate) const DEEP_SKY_TARGETS: [DeepSkyTarget; {len(targets)}] = [\n"
    for target, entry in zip(targets, entries):
        rust += "DeepSkyTarget {\n"
        for key in ("position_ly", "right", "up", "half_size_ly"):
            values = [f"{v:.15g}" for v in entry[key]]
            values = [v if "." in v or "e" in v else v + ".0" for v in values]
            rust += f"{key}: [{', '.join(values)}],\n"
        rust += "},\n"
    rust += "];\n"
    rust = subprocess.check_output(["rustfmt", "--edition", "2024", "--emit", "stdout"], input=rust, text=True)
    glsl = "// Generated by scripts/prepare-astronomy-nebulae.py; edit deep-sky-catalog.json.\n"
    glsl += f"const int DEEP_SKY_COUNT = {len(targets)};\n"
    for field, width in (("position_ly", 3), ("right", 3), ("up", 3), ("half_size_ly", 2), ("atlas_rect", 4)):
        glsl += f"const vec{width} DEEP_SKY_{field.upper()}[{len(targets)}] = vec{width}[{len(targets)}](\n"
        glsl += ",\n".join(f"    vec{width}({', '.join(f'{v:.12f}' for v in entry[field])})" for entry in entries)
        glsl += "\n);\n"
    return rust, glsl


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    manifest = ASSETS / "deep-sky-catalog.json"
    targets = json.loads(manifest.read_text())
    if not args.check:
        if args.source_dir is None:
            parser.error("--source-dir is required to rebuild the atlas")
        atlas = Image.new("RGB", (4 * TILE, 3 * TILE))
        font = ImageFont.truetype("DejaVuSans.ttf", 13)
        for index, target in enumerate(targets):
            path = args.source_dir / (target["id"] + ".jpg")
            assert hashlib.sha256(path.read_bytes()).hexdigest() == target["source_sha256"], path
            with Image.open(path) as source:
                image = source.convert("RGB")
            image.thumbnail((TILE - 32, TILE - 32), getattr(Image, "Resampling", Image).LANCZOS)
            x = index % 4 * TILE + (TILE - image.width) // 2
            y = index // 4 * TILE + (TILE - image.height) // 2
            # Attribution stays attached to the image, including in close-ups.
            draw = ImageDraw.Draw(image)
            lines = [target["name"], *textwrap.wrap(target["credit"], max(25, (image.width - 64) // 7))]
            top = image.height - 40 - len(lines) * 17
            draw.rectangle((24, top - 8, image.width - 24, image.height - 28), fill=(0, 0, 0))
            for line_index, line in enumerate(lines):
                draw.text((32, top + line_index * 17), line, font=font, fill=(210, 221, 231))
            atlas.paste(image, (x, y))
            target["atlas_rect"] = [x / atlas.width, y / atlas.height, image.width / atlas.width, image.height / atlas.height]
        atlas.save(ASSETS / "deep-sky-atlas.jpg", quality=94, subsampling=0, optimize=True)
        manifest.write_text(json.dumps(targets, ensure_ascii=False, indent=2) + "\n")
    rust, glsl = generated(targets)
    outputs = ((RUST, rust), (SHADERS / "deep_sky_catalog.glsl", glsl))
    for path, content in outputs:
        if args.check:
            assert path.read_text() == content, f"stale generated catalogue: {path}"
        else:
            path.write_text(content)
    print("Deep-sky catalogue: 12 observed fields, CPU/GPU geometry in sync")


if __name__ == "__main__":
    main()
